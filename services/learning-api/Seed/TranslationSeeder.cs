    public static async Task SeedEnglishAsync(LearningDbContext db, CancellationToken ct = default)
    {
        foreach (var (key, value) in English)
        {
            var existing = await db.Translations.FindAsync([ "en", key ], ct);
            if (existing is null)
            {
                db.Translations.Add(new TranslationRow
                {
                    Locale = "en",
                    Key = key,
                    Value = value
                });
            }
            else if (existing.Value != value)
            {
                // English catalog in code is the source of truth — refresh stale rows.
                existing.Value = value;
            }
        }

        await db.SaveChangesAsync(ct);
    }
